"""Slice the round 2 hairstyle corrections (art/source/round2/hairstyles/hair-fix-a.webp and its worn
twin) into per-view sprites and worn-proof crops.

Usage (from the repo root):
    python3 -I art/slice_round2_hair.py

The sheet has the pack2 layout (3 rows x 4 views: front, left = figure faces viewer-left, right,
back) and replaces three styles, keeping their ids (art/ART-REQUESTS-ROUND2.md, block C):
side-ponytail, crimped-twists, curly-bob. Slicing, cleanup and proof registration are
art/slice_pack2.py's (imported, not modified).

Outputs (full resolution, NOT shipped; art/fit_hair_pack2.py registers them and ships the game-size
sprites):
* art/sprites/round2/hair/<id>-<view>.webp
* art/proofs/round2/hair/<id>-<view>.webp and art/proofs/round2/manifest.json (the same entry format
  as art/proofs/pack2/manifest.json; fit_hair_pack2.py reads these ids from here)
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.dont_write_bytecode = True
_spec = importlib.util.spec_from_file_location("hc_slice_pack2", HERE / "slice_pack2.py")
P = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(P)
S = P.S

ROOT = HERE.parent
SRC = ROOT / "art" / "source" / "round2"
OUT = ROOT / "art" / "sprites" / "round2"
PROOFS = ROOT / "art" / "proofs" / "round2"
SHEET = "hairstyles/hair-fix-a.webp"
IDS = ["side-ponytail", "crimped-twists", "curly-bob"]


def main():
    P.SRC, P.PROOFS, P.ROWS = SRC, PROOFS, len(IDS)
    report = {}
    items = P.slice_sheet(SHEET, "hair", IDS, report)
    sprites = {}
    for it in items:
        rel = f"hair/{it['id']}-{it['view']}.webp"
        S.save(it["sprite"], OUT / rel)
        sprites[(it["id"], it["view"])] = (it["sprite"], it)
    proofs = P.make_proofs(SHEET, "hair", IDS, sprites, SRC / SHEET.replace(".webp", "-worn.webp"))
    man = {"version": 1,
           "note": "Generated by art/slice_round2_hair.py from art/source/round2/hairstyles/hair-fix-a(-worn).webp. "
                   "Entries as art/proofs/pack2/manifest.json; the sprites are art/sprites/round2/hair/<id>-<view>.webp.",
           "items": {}}
    for key, e in proofs.items():
        iid, view = key.split("/")
        e["worn_sheet"] = f"art/source/round2/{SHEET.replace('.webp', '-worn.webp')}"
        e["sprite"] = f"../../sprites/round2/hair/{iid}-{view}.webp"
        man["items"].setdefault(iid, {})[view] = e
        print(f"{iid:16s} {view:5s} offset={e['offset']} identical={e['registration']['identical_px']} "
              f"iou={e['registration']['iou']} flags={e['flags']}", file=sys.stderr)
    for iid in man["items"]:
        man["items"][iid] = {v: man["items"][iid][v] for v in P.VIEWS}
    PROOFS.mkdir(parents=True, exist_ok=True)
    (PROOFS / "manifest.json").write_text(json.dumps(man, indent=1, default=int) + "\n")


if __name__ == "__main__":
    main()
