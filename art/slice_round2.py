"""Slice the round 2 outfit and open-shoe corrections into per-view sprites + manifest.

Usage (from the repo root):
    python3 -I art/slice_round2.py [--contact DIR]

Inputs (art/source/round2/, real transparency, 4 columns = views front, left (figure faces
viewer-left), right, back):
* outfits/outfits-fix-adult.webp   rows: aqua-velour-tracksuit, puffer-vest-slip-dress,
                                         hoodie-dress-leg-warmers (leg warmers stacked under the dress)
* outfits/outfits-fix-little.webp  rows: raincoat-set, bear-onesie, ballet-wrap-set
* open-shoes/shoes-adult-open-{under,over}.webp   rows: jelly-sandals, flower-flip-flops, wedge-sandals
* open-shoes/shoes-little-open-{under,over}.webp  rows (2 only): toddler-sandals, jelly-shoes
  Each open shoe is split into the part under the foot (sole, insole: -under) and the part over it
  (straps, uppers: -over), drawn in the same place on both sheets, so the two layers register by
  their sheet boxes (manifest: source.box; `pairOffset` = where the over sprite (or pair part) sits
  relative to the under one).

Detection, alpha cleanup and pair / stacked splitting are art/slice_pack2.py's (imported, not
modified): see its docstring. Outputs (full resolution, NOT shipped; art/build_wear.py makes the
game-size sprites):
* art/sprites/round2/<category>/<id>-<view>[-under|-over][-l|-r].webp
* art/sprites/round2/manifest.json
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
sys.dont_write_bytecode = True
_spec = importlib.util.spec_from_file_location("hc_slice_pack2", HERE / "slice_pack2.py")
P = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(P)
S = P.S

ROOT = HERE.parent
SRC = ROOT / "art" / "source" / "round2"
OUT = ROOT / "art" / "sprites" / "round2"

# (sheet under art/source/round2, category, layer or None, rows)
SHEETS = [
    ("outfits/outfits-fix-adult.webp", "outfits-adult", None,
     ["aqua-velour-tracksuit", "puffer-vest-slip-dress", "hoodie-dress-leg-warmers"]),
    ("outfits/outfits-fix-little.webp", "outfits-little", None,
     ["raincoat-set", "bear-onesie", "ballet-wrap-set"]),
    ("open-shoes/shoes-adult-open-under.webp", "shoes-adult", "under",
     ["jelly-sandals", "flower-flip-flops", "wedge-sandals"]),
    ("open-shoes/shoes-adult-open-over.webp", "shoes-adult", "over",
     ["jelly-sandals", "flower-flip-flops", "wedge-sandals"]),
    ("open-shoes/shoes-little-open-under.webp", "shoes-little", "under",
     ["toddler-sandals", "jelly-shoes"]),
    ("open-shoes/shoes-little-open-over.webp", "shoes-little", "over",
     ["toddler-sandals", "jelly-shoes"]),
]


def slice_one(sheet, cat, layer, ids):
    # slice_pack2 reads sheets from its SRC and assumes 3 rows: point it at this sheet
    P.SRC = SRC
    P.ROWS = len(ids)
    report = {}
    items = P.slice_sheet(sheet, cat, ids, report)
    out = {}
    for it in items:
        iid, view, spr = it["id"], it["view"], it["sprite"]
        suf = f"-{layer}" if layer else ""
        rel = f"{cat}/{iid}-{view}{suf}.webp"
        S.save(spr, OUT / rel)
        entry = {"file": rel, "width": spr.width, "height": spr.height,
                 "source": {"sheet": f"art/source/round2/{sheet}", "box": it["box"], "column": it["column"]}}
        rep = {}
        parts = P.split_parts(iid, view, spr, rep)
        if parts:
            entry["parts"] = {}
            for pname, (part, off, ps) in parts.items():
                prel = f"{cat}/{iid}-{view}{suf}-{ps}.webp"
                S.save(part, OUT / prel)
                entry["parts"][pname] = {"file": prel, "width": part.width, "height": part.height, "offset": off}
        out[(iid, view)] = entry
    return out, report


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--contact", type=Path, help="write a review contact sheet per source sheet here")
    args = ap.parse_args(argv)
    man = {"version": 1,
           "note": "Generated by art/slice_round2.py from art/source/round2/*. Paths relative to this file. "
                   "Conventions as dist/assets/pack2/manifest.json (views, source.box in sheet px, parts with "
                   "offset inside the view sprite). Open shoes: views[view].under / .over (same keys), "
                   "pairOffset = over box top-left minus under box top-left (sheet px), per part for pairs.",
           "items": {}}
    for sheet, cat, layer, ids in SHEETS:
        res, rep = slice_one(sheet, cat, layer, ids)
        print(f"{sheet}: {len(res)} sprites", file=sys.stderr)
        for (iid, view), e in res.items():
            item = man["items"].setdefault(iid, {"category": cat, "views": {}})
            if layer:
                item["views"].setdefault(view, {})[layer] = e
            else:
                item["views"][view] = e
    for iid, item in man["items"].items():
        item["views"] = {v: item["views"][v] for v in P.VIEWS}
        for v, e in item["views"].items():
            if "under" in e and "over" in e:
                ub, ob = e["under"]["source"]["box"], e["over"]["source"]["box"]
                e["pairOffset"] = [ob[0] - ub[0], ob[1] - ub[1]]
                if e["under"].get("parts") and e["over"].get("parts"):
                    e["partOffset"] = {}
                    for side in ("left", "right"):
                        up, op = e["under"]["parts"][side], e["over"]["parts"][side]
                        e["partOffset"][side] = [ob[0] + op["offset"][0] - ub[0] - up["offset"][0],
                                                 ob[1] + op["offset"][1] - ub[1] - up["offset"][1]]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "manifest.json").write_text(json.dumps(man, indent=1) + "\n")
    if args.contact:
        args.contact.mkdir(parents=True, exist_ok=True)
        for iid, item in man["items"].items():
            tiles = []
            for v, e in item["views"].items():
                for k in (["under", "over"] if "under" in e else [None]):
                    ee = e[k] if k else e
                    tiles.append(Image.open(OUT / ee["file"]).convert("RGBA"))
            w = sum(t.width for t in tiles) + 10 * len(tiles)
            h = max(t.height for t in tiles)
            img = Image.new("RGBA", (w, h), (231, 122, 176, 255))
            x = 0
            for t in tiles:
                img.alpha_composite(t, (x, 0))
                x += t.width + 10
            img.convert("RGB").save(args.contact / f"{iid}.png")
    print(f"{len(man['items'])} items", file=sys.stderr)


if __name__ == "__main__":
    main()
